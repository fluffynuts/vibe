import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from drive import *
a = Agent("e2b")
a.prompt("Use the Bash tool with run_in_background=true to run exactly: sleep 40; echo BGDONE. Do NOT wait for it or poll it. Reply with just the word: started.")
a.wait_results(1, 60)
a.prompt("Now use the Bash tool in the FOREGROUND (not background) to run exactly: python3 -c \"import time; time.sleep(30); print('FGDONE')\"  Then reply with just the word: done.")
time.sleep(6)
n = len(a.results())
a.send({"type": "control_request", "request_id": "int-1", "request": {"subtype": "interrupt"}}, "control_request interrupt (mid-turn)")
ok = a.wait_results(n + 1, 20)
print(f"-- result after interrupt seen={ok}; alive={a.alive()}; rss={a.rss_mb()}MB")
print("-- idle: does the background task still call back after the interrupt?")
a.wait_results(n + 2, 50)
print(f"-- results: {len(a.results())}; alive={a.alive()}")
a.close()
