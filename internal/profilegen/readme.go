package profilegen

import (
	"errors"
	"os"
	"path/filepath"

	"vibe/internal/fscopy"
)

// ReadmeFile is the note a generated profile's folder holds, saying so.
const ReadmeFile = "README.md"

// readmeText says that vibe made the profile's files, and what happens to
// edits to them. A note of its own, not a header in those files: a header would
// be composed text, changing every profile's hash (so every sandbox would be
// rebuilt once), and could not go in files the agent reads as instructions or in
// JSON.
const readmeText = `# This profile was generated by vibe

vibe composed this profile from the features named in config.yaml. You may edit
its files, but a re-compose (` + "`vibe -C`" + `) or an automatic update replaces
them, and edits are lost. The profile is backed up first (` + "`vibe --restore`" + `
lists the backups), so you can get something back.

Two files describe the profile, for two different readers:

- config.yaml describes the sandbox itself: what is installed in it, its
  permissions and environment. It is read by the sandbox tooling (sbx) when the
  sandbox is made.
- settings.yaml is settings for vibe's own behaviour with this profile, such as
  the sandbox's memory limit, which agent it runs, or the ports it publishes.
  It is vibe's own: settings in ~/.vibe/settings.yaml apply to every profile,
  and this file overrides them for this one.

Two things in this folder are yours, and are carried across:

- user-preferences.yaml: the choices you make through vibe (theme, git author,
  model, effort). Edit it as you like: delete a line to be asked again, or to go
  back to the default.
- agent-instructions.md: your instructions for this profile's agent.

This note is not part of what makes the profile out of date or edited: rewrite it
or delete it as you like. vibe adds it only to a profile it generated, and only
when there isn't one.
`

// AddReadme gives the generated profile in dir a README.md saying so, unless it
// has one (the user may have rewritten it) or wasn't generated (a blank,
// copied or hand-written profile is the user's own, and says nothing of
// vibe). It says whether it added one.
func AddReadme(dir string) (bool, error) {
	if !IsGuided(dir) {
		return false, nil
	}
	path := filepath.Join(dir, ReadmeFile)
	if _, err := os.Stat(path); err == nil {
		return false, nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	return true, fscopy.WriteWholeMode(path, []byte(readmeText), 0o644)
}
